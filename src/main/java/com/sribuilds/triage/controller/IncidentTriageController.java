package com.sribuilds.triage.controller;

import com.sribuilds.triage.dto.DiagnosticReport;
import com.sribuilds.triage.dto.TriageRequest;
import com.sribuilds.triage.service.TriageOutcome;
import com.sribuilds.triage.service.TriageService;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpHeaders;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * REST entry point for incident triage.
 *
 * <p>Sets {@code X-Cache-Hit: true|false} to signal whether the response was
 * served from the Redis deduplication cache or freshly generated by the LLM.</p>
 */
@RestController
@RequestMapping("/api/v1/incidents")
@RequiredArgsConstructor
public class IncidentTriageController {

    /** Response header indicating the Redis cache disposition. */
    public static final String X_CACHE_HIT_HEADER = "X-Cache-Hit";

    private final TriageService triageService;

    @PostMapping("/triage")
    public ResponseEntity<DiagnosticReport> triage(@Valid @RequestBody TriageRequest request) {
        TriageOutcome outcome = triageService.triage(request);

        HttpHeaders headers = new HttpHeaders();
        headers.add(X_CACHE_HIT_HEADER, Boolean.toString(outcome.cacheHit()));

        return ResponseEntity.ok()
                .headers(headers)
                .body(outcome.report());
    }
}